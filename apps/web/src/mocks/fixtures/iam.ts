export function sessionFor(phone: string): SessionUser | null {
  const user = mockUsers.find((u) => u.phone === phone);
  if (!user) return null;
  const role = mockRoles.find((r) => r.id === user.roles[0]?.id);
  return {
    id: user.id,
    name: user.name,
    nameEn: user.nameEn,
    phone: user.phone,
    email: user.email,
    orgId: user.orgId,
    orgName: user.orgName,
    roles: user.roles.map((r) => r.code),
    roleNames: user.roles.map((r) => r.name),
    permissions: role?.permissions ?? [],
    dataScope: role?.dataScope ?? "SELF",
    allCustomers: role?.allCustomers ?? false,
    customerIds: role?.customers.map((c) => c.id) ?? [],
    locale: "zh-CN",
    preferences: {},
    mustChangePassword: false,
  };
}
